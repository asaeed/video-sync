const beats = (value = {}) => (value.bars ?? 0) * 4 + (value.beats ?? 0);

function hash(value) {
  let result = 2166136261;
  for (const character of value) {
    result ^= character.charCodeAt(0);
    result = Math.imul(result, 16777619);
  }
  return result >>> 0;
}

export function subjectFocusFor(sceneId, clipId) {
  const clipIndex = Number.parseInt(clipId.replace("clip-", ""), 10) - 1;
  const [x, y] = SUBJECT_FOCUS[sceneId]?.[clipIndex] ?? [0.5, 0.44];
  return { x, y };
}

function primaryClipId(visualLoop) {
  const coverage = new Map();
  for (const event of visualLoop.events) {
    const duration = beats(event.duration);
    const layerPenalty = Math.max(0, event.appearance.z) * 0.001;
    coverage.set(event.clipId, (coverage.get(event.clipId) ?? 0) + duration - layerPenalty);
  }
  return [...coverage.entries()].sort((left, right) => right[1] - left[1])[0]?.[0];
}

function motionFor(scene, visualLoop, clipId) {
  const seed = hash(`${scene.id}:${visualLoop.id}:${clipId}`);
  const focus = subjectFocusFor(scene.id, clipId);
  const subjectScale = 1.1 + (seed % 6) * 0.012;
  const zoomOut = seed % 5 === 0;
  const centered = { scale: 1, focus: { x: 0.5, y: 0.5 } };
  const subject = { scale: subjectScale, focus };
  return {
    type: "ken-burns",
    focusSource: "clip-subject",
    progress: "loop",
    easing: "ease-in-out",
    start: zoomOut ? subject : centered,
    end: zoomOut ? centered : subject,
  };
}

export function addAuthoredKenBurns(scene, visualLoops) {
  const variant = hash(scene.id) % 3;
  return visualLoops.map((visualLoop, loopIndex) => {
    // Keep the default loop raw and animate approximately one in every three
    // authored cue loops. Depending on the phase, that is two or three of A-G.
    if (loopIndex === 0 || (loopIndex + variant) % 3 !== 0) return visualLoop;
    const clipId = primaryClipId(visualLoop);
    if (!clipId) return visualLoop;
    const motion = motionFor(scene, visualLoop, clipId);
    return {
      ...visualLoop,
      events: visualLoop.events.map((event) => event.clipId === clipId
        ? { ...event, appearance: { ...event.appearance, motion } }
        : event),
    };
  });
}
